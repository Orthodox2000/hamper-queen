/**
 * scripts/setup-env.mjs
 * -----------------------------------------------------------------------------
 * Creates a ready-to-run `.env` so a new machine needs ONE command:
 *
 *   npm run setup                       local MongoDB (docker compose), generated owner password
 *   npm run setup -- --atlas "<uri>"    MongoDB Atlas connection string
 *   npm run setup -- --db hamper_queen_staging --admin-user supriya
 *   npm run setup -- --force            overwrite an existing .env
 *   npm run setup -- --if-missing       do nothing when .env already exists (used by db:setup)
 *
 * The generated owner password is printed ONCE and stored only in .env (mode 600)
 * until `npm run db:bootstrap` creates the owner and scrubs it.
 */

import { existsSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { randomBytes } from 'node:crypto';

const args = process.argv.slice(2);
const flag = (name) => args.includes(`--${name}`);
const value = (name, fallback) => {
  const i = args.indexOf(`--${name}`);
  return i >= 0 && args[i + 1] && !args[i + 1].startsWith('--') ? args[i + 1] : fallback;
};

const outFile = resolve(value('out', '.env'));

if (existsSync(outFile)) {
  if (flag('if-missing')) {
    console.log(`${outFile} already exists - leaving it untouched.`);
    process.exit(0);
  }
  if (!flag('force')) {
    console.error(`${outFile} already exists. Re-run with --force to overwrite it.`);
    process.exit(1);
  }
}

const atlasUri = value('atlas', '');
if (flag('atlas') && !/^mongodb(\+srv)?:\/\//.test(atlasUri)) {
  console.error('--atlas needs a connection string, e.g. --atlas "mongodb+srv://user:pass@cluster.mongodb.net/"');
  process.exit(1);
}

const uri = atlasUri || value('uri', 'mongodb://127.0.0.1:27017/');
const db = value('db', 'hamper_queen');
const baseUrl = value('base-url', 'http://localhost:3000');
const adminUser = value('admin-user', 'owner');
const adminPassword = value('admin-password', randomBytes(12).toString('base64url'));

const body = `# Generated by scripts/setup-env.mjs on ${new Date().toISOString()}
# See .env.example and docs/ENVIRONMENT.md for every option.

MONGODB_URI=${uri}
MONGODB_DB=${db}
HQ_BASE_URL=${baseUrl}

# Bootstrap-only: consumed (and commented out) by \`npm run db:bootstrap\`.
HQ_BOOTSTRAP_ADMIN_USER=${adminUser}
HQ_BOOTSTRAP_ADMIN_PASSWORD=${adminPassword}
`;

writeFileSync(outFile, body, { mode: 0o600 });

console.log(`Created ${outFile}`);
console.log(`  database : ${db} (${atlasUri ? 'Atlas' : 'local'})`);
console.log(`  admin    : ${adminUser} / ${adminPassword}   <- shown once, save it now`);
console.log('');
console.log('Next:');
if (!atlasUri) console.log('  npm run db:up        # start local MongoDB (needs Docker)');
console.log('  npm run db:bootstrap # create collections, indexes and the owner admin');
console.log('  npm run dev');
